import { useEffect, useState } from "react";
import { useTranslation } from "react-i18next";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { usePatchUpdateFlow } from "@/controllers/API/queries/flows/use-patch-update-flow";
import useAlertStore from "@/stores/alertStore";
import type { FlowType } from "@/types/flow";
import {
  buildWorkflowNotesUpdate,
  clearLegacyWorkflowNotes,
  getWorkflowNotes,
  type NodusWorkflowNotes,
} from "@/utils/nodus-workflow-notes";

type WorkflowNotesModalProps = {
  open: boolean;
  setOpen: (open: boolean) => void;
  flowData: FlowType;
};

type EditableNotes = Omit<NodusWorkflowNotes, "updatedAt">;

const EMPTY_NOTES: EditableNotes = {
  purpose: "",
  inputs: "",
  outputs: "",
  assumptions: "",
  usage: "",
};

const Field = ({
  label,
  value,
  placeholder,
  onChange,
  rows = 3,
}: {
  label: string;
  value: string;
  placeholder: string;
  onChange: (value: string) => void;
  rows?: number;
}) => (
  <label className="flex flex-col gap-2">
    <span className="text-sm font-medium text-foreground">{label}</span>
    <textarea
      value={value}
      onChange={(event) => onChange(event.target.value)}
      placeholder={placeholder}
      rows={rows}
      className="min-h-[5rem] w-full resize-y rounded-md border border-input bg-background px-3 py-2 text-sm text-foreground outline-none placeholder:text-muted-foreground focus-visible:ring-1 focus-visible:ring-ring"
    />
  </label>
);

export default function WorkflowNotesModal({
  open,
  setOpen,
  flowData,
}: WorkflowNotesModalProps) {
  const { t } = useTranslation();
  const [notes, setNotes] = useState<EditableNotes>(EMPTY_NOTES);
  const [lastUpdated, setLastUpdated] = useState("");
  const setSuccessData = useAlertStore((state) => state.setSuccessData);
  const setErrorData = useAlertStore((state) => state.setErrorData);
  const { mutateAsync: updateFlow } = usePatchUpdateFlow();

  useEffect(() => {
    if (!open) return;

    const saved = getWorkflowNotes(flowData);
    const { updatedAt, ...editable } = saved;
    setNotes(editable);
    setLastUpdated(updatedAt);
  }, [open, flowData.id]);

  const updateField = (field: keyof EditableNotes, value: string) => {
    setNotes((current) => ({ ...current, [field]: value }));
  };

  const handleSave = async () => {
    try {
      const { saved, data } = buildWorkflowNotesUpdate(flowData, notes);

      await updateFlow({
        id: flowData.id,
        data,
      });

      clearLegacyWorkflowNotes(flowData.id);
      setLastUpdated(saved.updatedAt);
      setSuccessData({ title: t("flow.notesSaved") });
      setOpen(false);
    } catch {
      setErrorData({ title: t("flow.notesSaveFailed") });
    }
  };

  const buildMarkdown = () =>
    [
      `# ${flowData.name}`,
      "",
      "## Purpose",
      notes.purpose.trim() || "_Not documented_",
      "",
      "## Inputs",
      notes.inputs.trim() || "_Not documented_",
      "",
      "## Outputs",
      notes.outputs.trim() || "_Not documented_",
      "",
      "## Assumptions & Constraints",
      notes.assumptions.trim() || "_Not documented_",
      "",
      "## Usage Notes",
      notes.usage.trim() || "_Not documented_",
      "",
      `Generated by NodusAI${lastUpdated ? ` — ${new Date(lastUpdated).toLocaleString()}` : ""}`,
      "",
    ].join("\n");

  const handleExportMarkdown = () => {
    try {
      const blob = new Blob([buildMarkdown()], {
        type: "text/markdown;charset=utf-8",
      });
      const url = URL.createObjectURL(blob);
      const link = document.createElement("a");
      const safeName = flowData.name
        .trim()
        .replace(/[^a-z0-9-_]+/gi, "-")
        .replace(/^-+|-+$/g, "")
        .toLowerCase();

      link.href = url;
      link.download = `${safeName || "workflow"}-notes.md`;
      document.body.appendChild(link);
      link.click();
      link.remove();
      URL.revokeObjectURL(url);

      setSuccessData({ title: t("flow.notesExported") });
    } catch {
      setErrorData({ title: t("flow.notesExportFailed") });
    }
  };

  return (
    <Dialog open={open} onOpenChange={setOpen}>
      <DialogContent className="max-h-[86vh] max-w-2xl overflow-y-auto">
        <DialogHeader>
          <DialogTitle>{t("flow.notesTitle")}</DialogTitle>
          <DialogDescription>
            {t("flow.notesDescription", { name: flowData.name })}
          </DialogDescription>
        </DialogHeader>

        <div className="grid gap-5 py-2">
          <Field
            label={t("flow.notesPurpose")}
            value={notes.purpose}
            placeholder={t("flow.notesPurposePlaceholder")}
            onChange={(value) => updateField("purpose", value)}
          />
          <div className="grid gap-5 md:grid-cols-2">
            <Field
              label={t("flow.notesInputs")}
              value={notes.inputs}
              placeholder={t("flow.notesInputsPlaceholder")}
              onChange={(value) => updateField("inputs", value)}
            />
            <Field
              label={t("flow.notesOutputs")}
              value={notes.outputs}
              placeholder={t("flow.notesOutputsPlaceholder")}
              onChange={(value) => updateField("outputs", value)}
            />
          </div>
          <Field
            label={t("flow.notesAssumptions")}
            value={notes.assumptions}
            placeholder={t("flow.notesAssumptionsPlaceholder")}
            onChange={(value) => updateField("assumptions", value)}
          />
          <Field
            label={t("flow.notesUsage")}
            value={notes.usage}
            placeholder={t("flow.notesUsagePlaceholder")}
            onChange={(value) => updateField("usage", value)}
            rows={4}
          />

          {lastUpdated && (
            <div className="text-xs text-muted-foreground">
              {t("flow.notesLastUpdated", {
                date: new Date(lastUpdated).toLocaleString(),
              })}
            </div>
          )}
        </div>

        <DialogFooter className="flex-col gap-2 sm:flex-row sm:justify-between">
          <Button variant="ghost" onClick={handleExportMarkdown}>
            {t("flow.exportNotesMarkdown")}
          </Button>
          <div className="flex gap-2">
            <Button variant="outline" onClick={() => setOpen(false)}>
              {t("common.cancel")}
            </Button>
            <Button onClick={() => void handleSave()}>{t("common.save")}</Button>
          </div>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
